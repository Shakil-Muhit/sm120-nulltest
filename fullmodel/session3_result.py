    ap.add_argument('--out', default='SESSION3_RESULT.md')
    a = ap.parse_args()
    ev = a.evidence_dir
    st = load(os.path.join(ev, 'session_status.json')) or {}
    cfg = load(os.path.join(ev, 'session3_config.json')) or {}
    man = load(os.path.join(ev, 'session_manifest.json')) or {}
    L = []
    L.append('# SESSION3_RESULT.md — Phase 3 experiments E1–E9 (generated by fullmodel/session3_result.py)')
    L.append(f"evidence: {ev} · manifest {man.get('manifest_id')} · repo {str(man.get('repo_commit'))[:12]} · GPU {(man.get('env') or {}).get('gpu')} · "
             f"audit verdict **{st.get('verdict', 'UNRESOLVED')}** ({st.get('complete_items')}/{st.get('total_items')} mandatory) · evidence grade **{st.get('evidence_grade', 'UNRESOLVED')}** · "
             f"shakedown={st.get('shakedown')} · headline restarts {cfg.get('headline_restarts')} · pair restarts {cfg.get('pair_restarts')}")
    L.append('')
    L.append('Conventions: matched differences are a − b in ms, median over eligible restarts of the per-block medians, with a block-level bootstrap interval '
             f'({BOOT_N} resamples, seed {BOOT_SEED}); + means the second arm is faster. Predictions are the registered defaults of prereg_amendments.md v0.2 unless the owner overrode them in §8b.')
    L.append('')
    # ---- E6
    L.append('## E6 — A/A control and restarts')
    L.append(f'Registered: {PRED["E6"]}')
    L.append('')
    L.append('| operating point | C3 − C3#2 median (ms) | CI95 (block level) | interval covers zero | file |')
    L.append('|---|---|---|---|---|')
    aa = load(os.path.join(ev, 'aa_stats.json')) or {}
    for k, v in sorted((aa.get('pairs') or {}).items()):
        if 'median_ms' not in v:
            L.append(f"| {k} | UNRESOLVED | | | {v.get('status')} |"); continue
        lo, hi = v['ci95_median_ms']
        L.append(f"| {v['chunk']} | {v['median_ms']:+.4f} | [{lo:+.4f}, {hi:+.4f}] | {'yes' if lo <= 0 <= hi else 'NO'} | {k} |")
    summ = load(os.path.join(ev, 'summary_full.json')) or {}
    L.append('')
    L.append('Headline cells over the session restarts (collect_full.py; HEADLINE requires every restart eligible and SDR PASS in r1):')
    L.append('')
    L.append('| arm | O | status | headline (ms) | restart spread (ms) | per-restart min-of-medians |')
    L.append('|---|---|---|---|---|---|')
    for key, c in sorted((summ.get('cells') or {}).items()):
        arm, O = key.rsplit('_', 1)
        if arm in ('C3', 'H', 'A', 'C1') and int(O) in OPS:
            L.append(f"| {arm} | {O} | {c.get('headline_status')} | {f(c.get('headline_ms'))} | {f(c.get('restart_spread_ms'))} | {c.get('per_restart_min_of_medians_ms')} |")
    L.append('')
    # ---- E3
    L.append('## E3 — Inductor graph partition (C1P vs C1, 8 s)')
    L.append(f'Registered: {PRED["E3"]}')
    r = pair_result(ev, 'C1', 'C1P', 352800)
    v, gl, cap, stg = gv_of(ev, 'C1P', 352800)
    L.append('')
    L.append(f"- C1 − C1P: {f(r.get('median_ms'), '+.4f')} ms {r.get('ci95_ms', '')} ({r.get('restarts', 0)} restarts; {r.get('status')}); C1 wall {f(r.get('a_wall_ms'))}, C1P wall {f(r.get('b_wall_ms'))} ms")
    L.append(f"- C1P node trace: {v}; graph launches/pass {f(gl, '.1f')}; captured kernels/pass {f(cap, '.1f')}; staging copies/pass {f(stg, '.1f')} (traces/graph_verify_C1P_352800.json); "
             f"C1 in session 2: 96 launches, 63 staging kernels per pass (docs/phase3/x1/x1_decomposition_352800.json)")
    ok = r.get('status') == 'ok' and abs(r['median_ms']) < 0.02 * (r.get('a_wall_ms') or 1e9)
    L.append(f"- Registered prediction (no material change): **{'confirmed' if ok else 'NOT confirmed'}**" + (' — partition is a finding, reported as such' if r.get('status') == 'ok' and not ok else ''))
    L.append('')
    # ---- E2
    L.append('## E2 — Repair × max-autotune (C3M vs C3)')
    L.append(f'Registered: {PRED["E2"]}')
    L.append('')
    L.append('| O | C3 − C3M (ms) | CI95 | restarts | C3 wall | C3M wall | SDR (C3M r1) | graph verify | Triton template GEMMs/pass | extern GEMMs/pass |')
    L.append('|---|---|---|---|---|---|---|---|---|---|')
    e2 = {}
    for O in OPS:
        r = pair_result(ev, 'C3', 'C3M', O); e2[O] = r
        s_, d_ = sdr_of(ev, 'C3M', O); v, gl, cap, stg = gv_of(ev, 'C3M', O)
        tc = load(os.path.join(ev, 'traces', f'template_count_C3M_{O}.json')) or {}
        L.append(f"| {O} | {f(r.get('median_ms'), '+.4f')} | {r.get('ci95_ms', r.get('status'))} | {r.get('restarts', 0)} | {f(r.get('a_wall_ms'))} | {f(r.get('b_wall_ms'))} | {s_} ({f(d_, '+.4f')} dB) | {v} ({f(cap, '.0f')} kernels) | {f(tc.get('triton_template_kernels_per_pass'), '.0f')} ({f(tc.get('triton_template_time_ms_per_pass'), '.3f')} ms) | {f(tc.get('extern_gemm_kernels_per_pass'), '.0f')} |")
    r8, r1 = e2[352800], e2[4410]
    ok8 = r8.get('status') == 'ok' and 1.0 <= r8['median_ms'] <= 4.48
    ok1 = r1.get('status') == 'ok' and abs(r1['median_ms']) <= 0.05
    L.append('')
    L.append(f"- Registered prediction: 8 s **{'confirmed' if ok8 else 'NOT confirmed'}** ({f(r8.get('median_ms'), '+.3f')} ms vs [1.0, 4.48]); 4410 **{'confirmed' if ok1 else 'NOT confirmed'}** ({f(r1.get('median_ms'), '+.3f')} ms vs |Δ| ≤ 0.05)")
    L.append('- Template kernel names carrying `_to_copy` mean the weight cast is fused into the Triton GEMM template, so part of X6a is realized by E2 as well (ledger note).')
    L.append('')
    # ---- E1
    L.append('## E1 — Weight re-cast removal (X6a): C3F (freezing), C3G (freezing without nn-module inlining), C3P (pre-cast)')
    L.append(f'Registered: {PRED["E1"]}')
    br = load(os.path.join(ev, 'e1_branch.json')) or {}
    L.append(f"- Branch record (e1_branch.json): run_C3P = {br.get('run_C3P')}; reasons {br.get('reasons')}; lane stopped by SDR: {br.get('e1_lane_stopped_sdr')}")
    L.append('')
    L.append('| arm | O | C3 − arm (ms) | CI95 | restarts | arm wall | cast kernels/pass (C3 → arm) | cast time ms/pass (C3 → arm) | graph verify (kernels) | SDR (r1) |')
    L.append('|---|---|---|---|---|---|---|---|---|---|')
    best = {O: None for O in OPS}
    for arm in ('C3F', 'C3G', 'C3P'):
        for O in OPS:
            r = pair_result(ev, 'C3', arm, O)
            if r.get('status') != 'ok' and not glob.glob(os.path.join(ev, f'matched_C3_{arm}_c{O}_m*.json')):
                continue
            k0, t0 = cc_of(ev, 'C3', O); k1, t1 = cc_of(ev, arm, O)
            v, gl, cap, stg = gv_of(ev, arm, O); s_, d_ = sdr_of(ev, arm, O)
            L.append(f"| {arm} | {O} | {f(r.get('median_ms'), '+.4f')} | {r.get('ci95_ms', r.get('status'))} | {r.get('restarts', 0)} | {f(r.get('b_wall_ms'))} | {f(k0, '.0f')} → {f(k1, '.0f')} | {f(t0, '.3f')} → {f(t1, '.3f')} | {v} ({f(cap, '.0f')}) | {s_} ({f(d_, '+.4f')} dB) |")
            if r.get('status') == 'ok' and (best[O] is None or r['median_ms'] > best[O][1]):
                best[O] = (arm, r['median_ms'])
    L.append('')
    for O, need in ((352800, 0.55), (4410, 0.60)):
        b = best[O]
        L.append(f"- {O}: best realized {b[0] if b else 'UNRESOLVED'} {f(b[1] if b else None, '+.3f')} ms vs registered ≥ {need} ms → **{'confirmed' if b and b[1] >= need else 'NOT confirmed'}**; "
                 f"X6a ceiling {0.9198 if O == 352800 else 0.8574} ms (LEDGER.md) → {'realized EXCEEDS the ceiling: freezing folds more than the casts (attribution incomplete)' if b and b[1] > (0.9198 if O == 352800 else 0.8574) else 'within the ceiling'}")
    L.append('')
    # ---- E9
    L.append('## E9 — Held-out crossover (C3 vs H at 176,400 and 264,600)')
    L.append(f'Registered: {PRED["E9"]}')
    e9 = load(os.path.join(ev, 'e9_check.json'))
    if not e9:
        L.append(f"- UNRESOLVED: no e9_check.json (held-out lengths run only in the pod session; shakedown={cfg.get('shakedown')})")
    else:
        L.append(f"- Verdict **{e9.get('verdict')}**; registered variant {e9.get('registered_variant')}; predicted L* {e9.get('crossover_L_star_pred')}; tolerance {e9.get('tolerance_ms')} ms")
        L.append('')
        L.append('| L | predicted C3 − H (ms) | observed (ms) | CI95 | error (ms) | sign predicted / observed | sign correct | within tolerance |')
        L.append('|---|---|---|---|---|---|---|---|')
        for Lk, r in (e9.get('held_out') or {}).items():
            L.append(f"| {Lk} | {f(r.get('predicted_C3_minus_H_ms'), '+.3f')} | {f(r.get('observed_C3_minus_H_ms (median over restarts of block medians)'), '+.3f')} | {r.get('observed_ci95_block_level_ms', '')} | {f(r.get('error_ms'), '+.3f')} | {r.get('sign_predicted')} / {r.get('sign_observed')} | {r.get('sign_correct')} | {r.get('within_tolerance')} |")
        for Lk in HELD:
            aa_ = pair_result(ev, 'C3', 'C3', Lk)
            L.append(f"- A/A at {Lk}: {f(aa_.get('median_ms'), '+.4f')} ms {aa_.get('ci95_ms', aa_.get('status'))}")
    L.append('')
