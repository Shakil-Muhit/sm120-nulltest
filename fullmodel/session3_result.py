    # ---- E7
    L.append('## E7 — PDL evidence (boundary microbenchmark)')
    L.append(f'Registered: {PRED["E7"]}')
    bb = load(os.path.join(ev, 'boundary_bench.json')) or {}
    ta = load(os.path.join(ev, 'boundary_bench_trace_analysis.json')) or {}
    L.append('')
    L.append('| chain / mode | slope µs/node (unprofiled) | intercept µs | trace gap µs (N1000) | overlap observed (N1000) |')
