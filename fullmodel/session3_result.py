    L.append('| arm | O | variant | depth | width factor | params fp16 (MB) | mask-est fp16 (MB) | wall median over restarts (ms) | cast ms/pass (4410 trace) | boundary count (4410 trace) | kernel sum / span (ms) |')
    L.append('|---|---|---|---|---|---|---|---|---|---|---|')
