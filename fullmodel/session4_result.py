"""SESSION4_RESULT.md generator (Phase 4). Every number is computed from the cited session-4
evidence files through the shared reducer (e_tools.pair_series: validator, manifest join,
per-repeat differences from samples, clock-flagged repeats excluded) and stats_v2 (cluster
bootstrap). Verdicts use the thresholds recorded in session4_config.json (declared in
docs/phase4/PLAN.md before measurement). Missing inputs print UNRESOLVED.
"""
import argparse
import glob
import json
import os
import statistics
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)
import e_tools  # noqa: E402
import stats_v2  # noqa: E402


def load(p):
    try:
        return json.load(open(p))
    except Exception:
        return None


def f(v, spec='.4f'):
    return 'UNRESOLVED' if v is None else (format(v, spec) if isinstance(v, (int, float)) else str(v))


def verdict(point, ci, thr):
    if point is None or ci is None:
        return 'UNRESOLVED'
    lo, hi = ci
    if lo > 0 and point >= thr:
        return 'second arm faster'
    if hi < 0 and point <= -thr:
        return 'first arm faster'
    if -thr <= lo and hi <= thr:
        return 'practical tie'
    return 'unresolved'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--evidence-dir', required=True)
    ap.add_argument('--out', default='SESSION4_RESULT.md')
    a = ap.parse_args()
    ev = a.evidence_dir
    st = load(os.path.join(ev, 'session_status.json')) or {}
    cfg = load(os.path.join(ev, 'session4_config.json')) or {}
    man = load(os.path.join(ev, 'session_manifest.json')) or {}
    thr = {int(k): v for k, v in (cfg.get('thresholds_ms') or {}).items()}
    manifest_id, flags = e_tools.drift_context(ev)
    L = []
    L.append('# SESSION4_RESULT.md — Phase-4 follow-up (generated by fullmodel/session4_result.py)')
    L.append(f"evidence: {ev} · manifest {man.get('manifest_id')} · repo {str(man.get('repo_commit'))[:12]} · GPU {(man.get('env') or {}).get('gpu')} {(man.get('env') or {}).get('gpu_uuid')} · "
             f"audit **{st.get('verdict', 'UNRESOLVED')}** ({st.get('complete_items')}/{st.get('total_items')} mandatory) · grade **{st.get('evidence_grade', 'UNRESOLVED')}** · plan sha {str(cfg.get('plan_sha256'))[:12]}")
    L.append('')
    L.append('Conventions: matched differences are first − second arm in ms (+ = second arm faster); point = median over eligible restarts of per-restart medians of per-repeat block-median differences; '
             'interval = two-level cluster bootstrap (restarts, then repeats; 10,000 draws, seed 20260921); clock-flagged repeats excluded; restart medians shown. '
             f"Practical thresholds (declared in advance): {thr} ms. Verdict rule: 'x faster' needs the interval to exclude zero and |point| ≥ threshold; 'practical tie' needs the interval inside ±threshold.")
    L.append('')

    def pair_block(label, x, y, O, extra=''):
        r = stats_v2.pair_stats(ev, x, y, O, manifest_id, flags)
        if not r:
            L.append(f"| {O} | {x} vs {y} | UNRESOLVED (no eligible pair) | | | | |"); return None
        pt = r['point_estimate_ms (median of restart medians)']; ci = r['ci95_cluster_bootstrap_ms (revised; same statistic)']
        v = verdict(pt, ci, thr.get(O, 0.3))
        L.append(f"| {O} | {x} vs {y} | {pt:+.4f} | [{ci[0]:+.4f}, {ci[1]:+.4f}] | {[round(m, 3) for m in r['restart_medians_ms']]} | {r['repeats_used']} | **{v}**{extra} |")
        return r
    hdr = '| O | pair | point (ms) | cluster CI95 | restart medians | clean repeats | verdict |'
    sep = '|---|---|---|---|---|---|---|'
    # P0
    L.append('## P0 — A/A control (C3 vs C3)'); L.append(''); L.append(hdr); L.append(sep)
    for O in [int(x) for x in (cfg.get('aa_lengths') or [])]:
        pair_block('P0', 'C3', 'C3', O)
    L.append('')
    # PA
    L.append('## PA — C3 vs H ranking under matched conditions (same GPU, same session)'); L.append('')
    L.append('Replication at sampled lengths; no crossover location is interpolated. The old 8 s paired result (Sep 20, other card) and the Phase-3 4 s / 6 s pairs stay separate.'); L.append('')
    L.append(hdr); L.append(sep)
    for O in [int(x) for x in (cfg.get('pa_lengths') or [])]:
        pair_block('PA', 'C3', 'H', O)
    L.append('')
    # PB
    L.append('## PB — C1P runner discrepancy @352800'); L.append('')
    summ = load(os.path.join(ev, 'summary_full.json')) or {}
    c = (summ.get('cells') or {}).get('C1P_352800') or {}
    c1 = (summ.get('cells') or {}).get('C1_352800') or {}
    L.append(f"- standalone unprofiled C1P (r1..r3): {c.get('headline_status')} headline {f(c.get('headline_ms'))} ms, per restart {c.get('per_restart_min_of_medians_ms')}")
    if c1:
        L.append(f"- standalone unprofiled C1 (if run): {c1.get('headline_status')} {f(c1.get('headline_ms'))} ms")
    L.append(''); L.append(hdr); L.append(sep)
    pair_block('PB', 'C1', 'C1P', 352800, ' (control built first)')
    pair_block('PB', 'C1P', 'C1', 352800, ' (order swapped: C1P built first)')
    L.append('')
    for x, y, tag in (('C1', 'C1P', 'm1'), ('C1P', 'C1', 'm1')):
        m = load(os.path.join(ev, f'matched_{x}_{y}_c352800_{tag}.json')) or {}
        arms = m.get('arms') or {}
        L.append(f"- matched {x} then {y} ({tag}): " + '; '.join(f"{k}: breaks {(v.get('graph_gate') or {}).get('graph_break_count')}, recorded cudagraphs {((v.get('graph_gate') or {}).get('cudagraph_counters') or {}).get('cudagraph_recorded_non_static_inputs')}, wall {f(v.get('min_of_medians_ms'))}" for k, v in arms.items()))
    for arm in ('C1P', 'C1'):
        r1 = load(os.path.join(ev, f'full_{arm}_c352800_r1.json')) or {}
        tr = load(os.path.join(ev, f'full_{arm}_c352800_trace.json')) or {}
        g1 = (r1.get('graph_gate') or {}); gt = (tr.get('graph_gate') or {})
        L.append(f"- standalone {arm}: r1 breaks {g1.get('graph_break_count')}, recorded {((g1.get('cudagraph_counters') or {}).get('cudagraph_recorded_non_static_inputs'))}, wall {f(r1.get('min_of_medians_ms'))}; traced block breaks {gt.get('graph_break_count')}, block median {f(statistics.median(tr['timing']['blocks'][0]['latency_ms_per_iter']) if tr.get('timing') else None)}")
    mt = load(os.path.join(ev, 'traces', 'matched_trace_C1_C1P_352800_p1.json')) or {}
    if mt.get('status') == 'ok':
        L.append(''); L.append('Profiled matched process (repeat 0 under nsys; aligned per-arm pass windows; medians over 50 passes):'); L.append('')
        L.append('| arm | wall µs | GPU busy µs | GPU span µs | GPU idle within window µs | kernels | memops | graph launches | memcpy API | sync API | API union µs | profiled block ms | unprofiled blocks ms |')
        L.append('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
        for arm, v in mt['arms'].items():
            L.append(f"| {arm} | {f(v.get('median_wall_us'), '.1f')} | {f(v.get('median_gpu_busy_us'), '.1f')} | {f(v.get('median_gpu_span_us'), '.1f')} | {f(v.get('median_gpu_idle_within_window_us'), '.1f')} | {f(v.get('median_kernels'), '.0f')} | {f(v.get('median_memops'), '.0f')} | {f(v.get('median_graph_launches'), '.0f')} | {f(v.get('median_memcpy_api_calls'), '.0f')} | {f(v.get('median_sync_api_calls'), '.0f')} | {f(v.get('median_api_union_us'), '.1f')} | {f(v.get('profiled_block_median_ms'))} | {f(v.get('unprofiled_blocks_median_ms'))} |")
        L.append(f"- {mt.get('note')}")
    else:
        L.append(f"- profiled matched process: UNRESOLVED ({mt.get('status')})")
    for arm in ('C1P', 'C1'):
        gv = load(os.path.join(ev, 'traces', f'graph_verify_{arm}_352800.json')) or {}; m_ = gv.get('median') or {}
        tv = load(os.path.join(ev, 'traces', f'timing_views_{arm}_352800.json')) or {}; med = tv.get('median_us') or {}
        L.append(f"- standalone traced {arm}: {gv.get('verdict', 'UNRESOLVED')}; graph launches/pass {f(m_.get('graph_launch_calls'), '.1f')}, staging {f(m_.get('input_staging_kernels'), '.1f')}, uncaptured {f(m_.get('uncaptured_model_kernels'), '.1f')}; kernel sum {f((med.get('sum_ns') or 0) / 1e3, '.3f')} ms, span {f((med.get('span_ns') or 0) / 1e3, '.3f')} ms")
    L.append('')
    # PC
    L.append('## PC1–PC4 — configuration interactions'); L.append(''); L.append(hdr); L.append(sep)
    for O in [int(x) for x in (cfg.get('pc_ops') or [4410, 352800])]:
        pair_block('PC1', 'C3', 'C3I', O, ' (inlining off, freezing off vs C3)')
        pair_block('PC2', 'C3I', 'C3G', O, ' (freezing on vs off, both inlining off)')
        pair_block('PC3', 'C3M', 'C3MG', O, ' (max-autotune: + freezing/inlining off)')
        pair_block('PC4', 'H', 'HG', O, ' (pad-and-batch: + freezing/inlining off)')
    L.append('')
    L.append('Separately measured gains are not added; PC3 and PC4 measure the compositions directly.')
    L.append('')
    # PQ
    L.append('## PQ — quality gates, graph deployment, cast and template counts of the new arms'); L.append('')
    L.append('| arm | O | SDR (r1) | graph verify (kernels) | cast kernels/pass | cast ms/pass | template GEMMs/pass | extern GEMMs/pass | wall r1 (ms) |'); L.append('|---|---|---|---|---|---|---|---|---|')
    for arm in ('C3', 'C3I', 'C3G', 'C3MG', 'HG', 'C3M', 'H'):
        for O in (4410, 352800):
            r1 = load(os.path.join(ev, f'full_{arm}_c{O}_r1.json')) or {}
            g = r1.get('sdr_gate') or {}
            gv = load(os.path.join(ev, 'traces', f'graph_verify_{arm}_{O}.json')) or {}
            cc = load(os.path.join(ev, 'traces', f'cast_count_{arm}_{O}.json')) or {}
            tc = load(os.path.join(ev, 'traces', f'template_count_{arm}_{O}.json')) or {}
            if not (r1 or gv or cc):
                continue
            L.append(f"| {arm} | {O} | {g.get('status', '—')} ({f(g.get('mean_delta_sdr_ref_db'), '+.4f')} dB) | {gv.get('verdict', '—')} ({f((gv.get('median') or {}).get('captured_model_kernels'), '.0f')}) | {f(cc.get('cast_kernels_per_pass'), '.0f')} | {f(cc.get('cast_time_ms_per_pass'), '.3f')} | {f(tc.get('triton_template_kernels_per_pass'), '.0f')} | {f(tc.get('extern_gemm_kernels_per_pass'), '.0f')} | {f(r1.get('min_of_medians_ms'))} |")
    L.append('')
    L.append('## Audit')
    bad = [i for i in (st.get('items') or []) if not i['complete'] and not i.get('optional')]
    L.append(f"- verdict {st.get('verdict')}; mandatory incomplete items: {len(bad)}" + (': ' + '; '.join(i['item'][:100] for i in bad[:16]) if bad else ''))
    opt = [i for i in (st.get('items') or []) if not i['complete'] and i.get('optional')]
    L.append(f"- optional incomplete items: {len(opt)}" + (': ' + '; '.join(i['item'][:80] for i in opt[:8]) if opt else ''))
    fl = flags.get('pairs') or {}
    L.append(f"- clock-flagged repeats (excluded): {len(fl)} pair records; cells flagged across restarts: {list(flags.get('cells') or {})}")
    with open(a.out, 'w') as fh:
        fh.write('\n'.join(L) + '\n')
    print(f'-> {a.out} ({len(L)} lines)')


if __name__ == '__main__':
    main()
